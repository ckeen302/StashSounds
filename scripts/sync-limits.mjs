#!/usr/bin/env node
/**
 * Writes public.app_limits() from packages/contracts/limits.json into a migration, so the database
 * checks the same limits as the web app and the worker. Lead-only, like every migration.
 *
 *   node scripts/sync-limits.mjs            write supabase/migrations/<timestamp>_limits.sql
 *   node scripts/sync-limits.mjs --check    exit 1 if the latest limits migration is stale
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const limits = JSON.parse(readFileSync(join(root, "packages/contracts/limits.json"), "utf8"));
delete limits.$comment;
const body = JSON.stringify(limits);

export function render(json) {
  return `-- Generated by scripts/sync-limits.mjs from packages/contracts/limits.json. Do not edit by hand.
create or replace function public.app_limits() returns jsonb
language sql immutable
set search_path = ''
as $limits$ select '${json.replaceAll("'", "''")}'::jsonb $limits$;
`;
}

const dir = join(root, "supabase/migrations");
const latest = readdirSync(dir).filter((f) => f.endsWith("_limits.sql")).sort().at(-1);

if (process.argv.includes("--check")) {
  if (!latest || readFileSync(join(dir, latest), "utf8") !== render(body)) {
    console.error("supabase/migrations is out of date with limits.json. Run: node scripts/sync-limits.mjs");
    process.exit(1);
  }
  console.log(`limits migration ${latest} is current`);
} else {
  const stamp = process.argv[2] ?? new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const name = `${stamp}_limits.sql`;
  writeFileSync(join(dir, name), render(body));
  console.log(`wrote supabase/migrations/${name}`);
}
