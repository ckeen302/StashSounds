#!/usr/bin/env node
// Demo media for the browser-only demo (ticket 137). Lead-owned.
//
// For each generated loop fixture it makes what the worker makes for a real upload:
//   - a loudness-matched MP3 preview: loudnorm in two passes to limits.loudness, 44.1 kHz stereo,
//     LAME at limits.preview's bitrate for the loop's length (the worker's encode_preview);
//   - limits.waveform.peakPoints peaks of the preview's mono mix, 0..255 (the worker's mono_peaks),
//     base64 as the contracts' encodePeaks writes them.
// The tempo, key, bars and loop length come from fixtures/manifest.json, the values the worker's
// tests hold its analysis to.
//
// Writes:
//   apps/web/public/demo/media/<slug>.mp3      (gitignored; regenerated by this script)
//   apps/web/src/demo/generated/loops.json     (committed; the Interface lane reads only this)
//
// Usage: node scripts/build-demo.mjs   (needs ffmpeg with libmp3lame on PATH)
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const limits = JSON.parse(readFileSync(join(root, "packages/contracts/limits.json"), "utf8"));
const manifest = JSON.parse(readFileSync(join(root, "fixtures/manifest.json"), "utf8"));
const mediaDir = join(root, "apps/web/public/demo/media");
const outJson = join(root, "apps/web/src/demo/generated/loops.json");
const SAMPLE_RATE = 44100;

function ffmpeg(args, { capture = false } = {}) {
  const r = spawnSync("ffmpeg", ["-hide_banner", "-nostdin", "-threads", "1", ...args], {
    maxBuffer: 1 << 28,
    encoding: capture ? "buffer" : undefined,
  });
  if (r.status !== 0) throw new Error(`ffmpeg ${args.join(" ")}\n${r.stderr?.toString().slice(-2000)}`);
  return r;
}

function loudnorm(src) {
  const { targetLufs, truePeakDb } = limits.loudness;
  const r = ffmpeg(["-i", src, "-af", `loudnorm=I=${targetLufs}:TP=${truePeakDb}:LRA=50:print_format=json`, "-f", "null", "-"]);
  const err = r.stderr.toString();
  const json = JSON.parse(err.slice(err.lastIndexOf("{"), err.lastIndexOf("}") + 1));
  return (
    `loudnorm=I=${targetLufs}:TP=${truePeakDb}:LRA=50` +
    `:measured_I=${json.input_i}:measured_TP=${json.input_tp}:measured_LRA=${json.input_lra}` +
    `:measured_thresh=${json.input_thresh}:offset=${json.target_offset}:linear=true`
  );
}

function peaks(mp3, points) {
  const r = ffmpeg(["-i", mp3, "-ac", "1", "-ar", String(SAMPLE_RATE), "-f", "f32le", "-"], { capture: true });
  const buf = r.stdout;
  const samples = new Float32Array(buf.buffer, buf.byteOffset, Math.floor(buf.length / 4));
  const n = samples.length;
  const out = new Uint8Array(points);
  for (let i = 0; i < points; i++) {
    const lo = Math.floor((i * n) / points);
    const hi = Math.floor(((i + 1) * n) / points);
    let m = 0;
    for (let j = lo; j < hi; j++) m = Math.max(m, Math.abs(samples[j]));
    out[i] = Math.min(255, Math.round(m * 255));
  }
  return Buffer.from(out).toString("base64");
}

const loops = manifest.fixtures.filter((f) => f.path.startsWith("generated/loops/"));
if (loops.length === 0) throw new Error("no loop fixtures in fixtures/manifest.json");
mkdirSync(mediaDir, { recursive: true });
mkdirSync(dirname(outJson), { recursive: true });

const result = [];
for (const f of loops) {
  const src = join(root, "fixtures", f.path);
  const stem = basename(f.path).replace(/\.[^.]+$/, "");
  const slug = stem.toLowerCase().replace(/#/g, "s").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const { bpm, bars, key, loopSamples, sampleRate } = f.expect;
  const durationMs = Math.round((loopSamples / sampleRate) * 1000);
  const p = limits.preview;
  const kbps = durationMs <= p.loopShortMaxMs ? p.loopBitrateKbpsShort : p.loopBitrateKbpsLong;
  const mp3 = join(mediaDir, `${slug}.mp3`);
  ffmpeg([
    "-i", src, "-af", `${loudnorm(src)},aresample=${SAMPLE_RATE}`, "-ar", String(SAMPLE_RATE), "-ac", "2",
    "-map_metadata", "-1", "-c:a", "libmp3lame", "-b:a", `${kbps}k`, "-f", "mp3", "-y", mp3,
  ]);
  const bytes = statSync(mp3).size;
  if (bytes > p.loopMaxBytes) throw new Error(`${slug}: preview ${bytes} B over limits.preview.loopMaxBytes`);
  result.push({
    slug,
    fixture: f.path,
    bpm,
    bars,
    key,
    loopSamples,
    sampleRate,
    durationMs,
    preview: {
      path: `demo/media/${slug}.mp3`,
      bytes,
      sha256: createHash("sha256").update(readFileSync(mp3)).digest("hex"),
      kbps,
    },
    peaks: peaks(mp3, limits.waveform.peakPoints),
  });
  console.log(`${slug}: ${bpm} BPM, ${bars} bars, ${durationMs} ms, ${kbps} kbps, ${bytes} B`);
}

writeFileSync(
  outJson,
  JSON.stringify({ $comment: "Generated by scripts/build-demo.mjs from fixtures/. Do not edit.", loops: result }, null, 2) + "\n",
);
console.log(`wrote ${result.length} loops to ${outJson.slice(root.length + 1)}`);
