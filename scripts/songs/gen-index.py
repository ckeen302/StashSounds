#!/usr/bin/env python3
"""Writes apps/web/src/demo/midi/song-batches/index.ts, importing every batch file (esbuild has no
glob imports). Run after adding a batch: python3 scripts/songs/gen-index.py"""
import glob, os, re
d = os.path.join(os.path.dirname(__file__), "..", "..", "apps/web/src/demo/midi/song-batches")
files = sorted(os.path.basename(f) for f in glob.glob(os.path.join(d, "*.json")))
names = [re.sub(r"[^a-zA-Z0-9]", "_", f[:-5]) for f in files]
lines = ["// Generated by scripts/songs/gen-index.py: every song batch, in file order.", ""]
lines += [f'import b_{n} from "./{f}" with {{ type: "json" }};' for n, f in zip(names, files)]
lines += ["", "export const BATCHES: unknown[][] = [" + ", ".join(f"b_{n}" for n in names) + "];", ""]
open(os.path.join(d, "index.ts"), "w").write("\n".join(lines))
print(f"{len(files)} batch files")
